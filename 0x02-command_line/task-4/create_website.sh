#!/bin/bash
# Generates a basic website project.
# Usage: ./create_website.sh [output_directory]

DEFAULT_DIR="$HOME/radius-projects/website-project"
PROJECT_DIR="${1:-$DEFAULT_DIR}"

if [ -e "$PROJECT_DIR" ]; then
  echo "Error: '$PROJECT_DIR' already exists. Nothing was changed." >&2
  exit 1
fi

mkdir -p "$PROJECT_DIR/css" "$PROJECT_DIR/js" "$PROJECT_DIR/images" || exit 1

cat > "$PROJECT_DIR/index.html" <<'HTML'
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>My Website</title>
  <link rel="stylesheet" href="css/style.css">
</head>
<body>
  <h1>Welcome to My Website</h1>
  <p>This page was generated by a Bash script.</p>
  <script src="js/script.js"></script>
</body>
</html>
HTML

cat > "$PROJECT_DIR/css/style.css" <<'CSS'
body {
  font-family: Arial, sans-serif;
  margin: 2rem;
  background-color: #f4f4f4;
  color: #333;
}

h1 {
  color: #0057b8;
}
CSS

cat > "$PROJECT_DIR/js/script.js" <<'JS'
console.log("Website loaded successfully!");
JS

cat > "$PROJECT_DIR/README.md" <<'MD'
# Website Project

A basic website generated by a Bash script. It contains an HTML page,
a CSS stylesheet and a JavaScript file.
MD

cat > "$PROJECT_DIR/css/README.md" <<'MD'
# CSS Directory

This folder holds the stylesheets that control the look of the website.
MD

cat > "$PROJECT_DIR/js/README.md" <<'MD'
# JavaScript Directory

This folder holds the JavaScript files that add interactivity to the website.
MD

cat > "$PROJECT_DIR/images/README.md" <<'MD'
# Images Directory

This folder holds image files such as photos, icons and logos (.png, .jpg, .svg).
MD

echo "Website project created at: $(cd "$PROJECT_DIR" && pwd)"
